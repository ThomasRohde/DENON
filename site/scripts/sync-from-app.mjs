// Reads the app's design system and content and writes them for the site, so the site follows the app:
// - src/generated/tokens.css: the Dark and Light palettes, the Default skin's type and radius scales, the meter
//   materials (MeterPalette.Default and DefaultLight), as CSS custom properties.
// - src/generated/icons.json: the app's icon geometries (Themes/Icons.xaml, 24x24 view box).
// - src/generated/help.json: the in-app Help & Guide topics, shortcuts and ports (MainViewModel.Help.cs).
// - src/generated/versions.json: the app and plugin versions.
// - public/generated/: the app icon and the bundled Share Tech Mono font (OFL).
// Runs before `astro dev` and `astro build` (package.json).
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const site = join(dirname(fileURLToPath(import.meta.url)), "..");
const repo = join(site, "..");
const app = join(repo, "Denon.App.Desktop");
const read = (...p) => readFileSync(join(...p), "utf8");
const out = join(site, "src", "generated");
const pub = join(site, "public", "generated");
mkdirSync(out, { recursive: true });
mkdirSync(pub, { recursive: true });

const kebab = (name) =>
  name
    .replace(/([a-z])([A-Z0-9])/g, "$1-$2")
    .replace(/([0-9])([A-Z])/g, "$1-$2")
    .toLowerCase();
const css = (hex) => {
  if (hex.length === 9) {
    const a = parseInt(hex.slice(1, 3), 16) / 255;
    const [r, g, b] = [3, 5, 7].map((i) => parseInt(hex.slice(i, i + 2), 16));
    return `rgb(${r} ${g} ${b} / ${a.toFixed(3)})`;
  }
  return hex.toLowerCase();
};

// ---------------------------------------------------------------- palettes
const palette = (name) =>
  [...read(app, "Themes", "Palettes", `${name}.xaml`).matchAll(/<Color x:Key="(\w+)Color">(#[0-9A-Fa-f]{6,8})<\/Color>/g)]
    .map(([, key, hex]) => `  --${kebab(key)}: ${css(hex)};`)
    .join("\n");

// ---------------------------------------------------------------- skin (Default) type and radius scales
const skin = read(app, "Themes", "Skins", "Default.xaml");
const scale = [...skin.matchAll(/x:Key="(FontSize\d+|Radius\d+)">([\d.]+)</g)]
  .map(([, key, value]) => `  --app-${kebab(key)}: ${value}px;`)
  .join("\n");

// ---------------------------------------------------------------- meter materials (MeterPalette.cs)
const meterSource = read(app, "Controls", "MeterPalette.cs");
const rgb = (r, g, b) => `rgb(${r} ${g} ${b})`;
const defaults = Object.fromEntries(
  [...meterSource.matchAll(/public Color (\w+) \{ get; init; \} = Color\.FromRgb\((\d+), (\d+), (\d+)\)/g)].map(
    ([, key, r, g, b]) => [key, rgb(r, g, b)],
  ),
);
const heat = (block) =>
  [...block.matchAll(/\(([\d.]+), Color\.FromRgb\((\d+), (\d+), (\d+)\)\)/g)].map(([, o, r, g, b]) => [Number(o), rgb(r, g, b)]);
const defaultHeat = heat(meterSource.slice(meterSource.indexOf("public IReadOnlyList<(double Offset, Color Color)> LedHeat")));
const lightBlock = meterSource.slice(
  meterSource.indexOf("public static MeterPalette DefaultLight"),
  meterSource.indexOf("public static MeterPalette HiFiLight"),
);
const lightOverrides = Object.fromEntries(
  [...lightBlock.matchAll(/(\w+) = Color\.FromRgb\((\d+), (\d+), (\d+)\)/g)].map(([, key, r, g, b]) => [key, rgb(r, g, b)]),
);
const meterVars = (colors, ramp) =>
  [
    ...[
      "LeftAccent", "RightAccent", "FaceTop", "FaceMiddle", "FaceBottom", "PaperInk", "RedZone", "RedZoneInk",
      "NeedleTip", "NeedleBase", "HoodCenter", "HoodEdge", "LedScreen", "LedScreenEdge", "LedLabel",
      "PeakLampUnlitCenter", "SourceDenon",
    ].map((k) => `  --meter-${kebab(k)}: ${colors[k]};`),
    `  --meter-led-heat: linear-gradient(to top, ${ramp.map(([o, c]) => `${c} ${(o * 100).toFixed(0)}%`).join(", ")});`,
  ].join("\n");
const lightColors = { ...defaults, ...lightOverrides };
const lightHeat = heat(lightBlock);

writeFileSync(
  join(out, "tokens.css"),
  `/* Generated by scripts/sync-from-app.mjs from the app's Themes and MeterPalette. Do not edit. */
:root {
${scale}
  --font-display: "Segoe UI Variable Display", "Segoe UI", system-ui, -apple-system, "Helvetica Neue", Arial, sans-serif;
  --font-ui: "Segoe UI Variable Text", "Segoe UI", system-ui, -apple-system, "Helvetica Neue", Arial, sans-serif;
  --font-mono: "Cascadia Mono", Consolas, ui-monospace, "SF Mono", Menlo, monospace;
  --font-readout: "Share Tech Mono", "Cascadia Mono", Consolas, ui-monospace, monospace;
}
:root, :root[data-theme="dark"] {
  color-scheme: dark;
${palette("Dark")}
${meterVars(defaults, defaultHeat)}
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
    color-scheme: light;
${palette("Light").replace(/^ {2}/gm, "    ")}
${meterVars(lightColors, lightHeat).replace(/^ {2}/gm, "    ")}
  }
}
:root[data-theme="light"] {
  color-scheme: light;
${palette("Light")}
${meterVars(lightColors, lightHeat)}
}
`,
);

// ---------------------------------------------------------------- icons
const icons = Object.fromEntries(
  [...read(app, "Themes", "Icons.xaml").matchAll(/<Geometry x:Key="(\w+)">([^<]+)<\/Geometry>/g)].map(([, k, d]) => [k, d.trim()]),
);
writeFileSync(join(out, "icons.json"), JSON.stringify(icons, null, 2));

// ---------------------------------------------------------------- Help & Guide
const helpSource = read(app, "ViewModels", "MainViewModel.Help.cs");
const str = /"((?:[^"\\]|\\.)*)"/g;
const unescape = (s) => s.replace(/\\"/g, '"').replace(/\\\\/g, "\\").replace(/\\n/g, "\n");
const strings = (text) => [...text.matchAll(str)].map((m) => unescape(m[1]));
const arg = (block, name) => {
  const m = new RegExp(`\\b${name}:\\s*"((?:[^"\\\\]|\\\\.)*)"`).exec(block);
  return m ? unescape(m[1]) : null;
};
const list = (block, name) => {
  const startAt = block.search(new RegExp(`\\b${name}:\\s*\\[`));
  if (startAt < 0) return "";
  let depth = 0;
  for (let i = block.indexOf("[", startAt); i < block.length; i++) {
    if (block[i] === "[") depth++;
    if (block[i] === "]" && --depth === 0) return block.slice(block.indexOf("[", startAt) + 1, i);
  }
  return "";
};
const records = (text, size) => {
  const items = [];
  for (const m of text.matchAll(/new\s*\(([\s\S]*?)\)\s*,?\s*(?=new\s*\(|$)/g)) {
    const s = strings(m[1]);
    if (s.length >= size) items.push(s.slice(0, size));
  }
  return items;
};
const topics = helpSource
  .split("_allHelpTopics.Add(new HelpGuideTopic(")
  .slice(1)
  .map((block) => ({
    id: arg(block, "id"),
    badge: arg(block, "badge"),
    accent: arg(block, "accentHex"),
    category: arg(block, "category"),
    title: arg(block, "title"),
    subtitle: arg(block, "subtitle"),
    overview: arg(block, "overview"),
    steps: records(list(block, "steps"), 3).map(([n, title, body]) => ({ n, title, body })),
    tips: strings(list(block, "proTips")),
    faq: records(list(block, "troubleshooting"), 2).map(([q, a]) => ({ q, a })),
    shortcuts: /showShortcutsTable:\s*true/.test(block),
    ports: /showPortsTable:\s*true/.test(block),
  }))
  .filter((t) => t.id && t.title);
const table = (name, size) =>
  [...helpSource.matchAll(new RegExp(`${name}\\.Add\\(new\\(([^;]*?)\\)\\);`, "g"))].map((m) => strings(m[1]).slice(0, size));
writeFileSync(
  join(out, "help.json"),
  JSON.stringify(
    {
      topics,
      shortcuts: table("HelpShortcutsReference", 3).map(([keys, where, what]) => ({ keys, where, what })),
      ports: table("HelpPortsReference", 3).map(([port, service, use]) => ({ port, service, use })),
    },
    null,
    2,
  ),
);

// ---------------------------------------------------------------- versions
const version = (path) => /<Version>([^<]+)<\/Version>/.exec(readFileSync(path, "utf8"))?.[1];
writeFileSync(
  join(out, "versions.json"),
  JSON.stringify(
    {
      app: version(join(app, "Denon.App.Desktop.csproj")),
      chromecast: version(join(repo, "external-plugins", "Denon.Plugin.Chromecast", "Denon.Plugin.Chromecast.csproj")),
      appleTv: version(join(repo, "external-plugins", "Denon.Plugin.AppleTv", "Denon.Plugin.AppleTv.csproj")),
      homePod: version(join(repo, "external-plugins", "Denon.Plugin.HomePod", "Denon.Plugin.HomePod.csproj")),
    },
    null,
    2,
  ),
);

// ---------------------------------------------------------------- assets
copyFileSync(join(app, "denon_icon.png"), join(pub, "denon_icon.png"));
copyFileSync(join(app, "Themes", "Fonts", "ShareTechMono-Regular.ttf"), join(pub, "ShareTechMono-Regular.ttf"));

console.log(`synced: ${topics.length} help topics, ${Object.keys(icons).length} icons, app ${version(join(app, "Denon.App.Desktop.csproj"))}`);
